// Status baris jadwal relatif terhadap tanggal `now` (WIB): "done" | "current" | "upcoming"
export function getScheduleStatus(item, now) {
  if (!now) return "upcoming";
  const start = new Date(`${item.start}T00:00:00+07:00`);
  const end = new Date(`${item.end}T23:59:59+07:00`);
  if (now > end) return "done";
  if (now >= start) return "current";
  return "upcoming";
}
